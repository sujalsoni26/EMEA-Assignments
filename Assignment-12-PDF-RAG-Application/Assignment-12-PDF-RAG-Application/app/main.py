@app.get("/api/health", response_model=HealthResponse, tags=["meta"])
async def health(rag: RAGService = Depends(get_rag)) -> HealthResponse:
    """Check that Ollama is running and both models are installed."""
    client = rag.client
    base = {"llm_model": client.llm_model, "embedding_model": client.embedding_model}
    try:
        missing = await client.missing_models()
    except OllamaError as exc:
        return HealthResponse(status="unavailable", ollama_reachable=False, missing_models=[], message=exc.message, **base)
    if missing:
        commands = " and ".join(f"`ollama pull {m}`" for m in missing)
        return HealthResponse(status="degraded", ollama_reachable=True, missing_models=missing,
                              message=f"Missing model(s): {', '.join(missing)}. Run {commands}.", **base)
    return HealthResponse(status="ok", ollama_reachable=True, missing_models=[], message="Ready.", **base)


@app.get("/api/documents", response_model=DocumentListResponse, tags=["documents"])
async def list_documents(rag: RAGService = Depends(get_rag)) -> DocumentListResponse:
    documents = sorted(rag.store.documents.values(), key=lambda d: d.uploaded_at)
    return DocumentListResponse(
        documents=[DocumentModel(**{k: v for k, v in asdict(d).items() if k != "sha256"}) for d in documents],
        total_chunks=rag.store.chunk_count,
    )


@app.post(
    "/api/documents",
    response_model=UploadResponse,
    tags=["documents"],
    responses={
        207: {"model": UploadResponse, "description": "Some files were indexed and some failed."},
        400: {"model": ErrorResponse}, 413: {"model": ErrorResponse}, 415: {"model": ErrorResponse},
        422: {"model": ErrorResponse}, 503: {"model": ErrorResponse},
    },
)
async def upload_documents(
    request: Request,
    files: list[UploadFile] = File(..., description="One or more PDF files."),
    rag: RAGService = Depends(get_rag),
) -> JSONResponse:
    """Upload PDFs: extract text, split it into chunks, embed the chunks and add them to the index.

    Each file is processed independently and gets its own result. If every file
    fails, the response uses the status code of the first failure.
    """
    if len(files) > settings.max_files_per_upload:
        return JSONResponse(
            status_code=400,
            content=error_body("too_many_files", f"Please upload at most {settings.max_files_per_upload} files at a time."),
        )

    results: list[UploadResult] = []
    first_error: tuple[int, str, str] | None = None
    for upload in files:
        name = upload.filename or "unnamed file"
        data = await upload.read(settings.max_file_bytes + 1)
        try:
            async with request.app.state.index_lock:
                record = await rag.ingest_pdf(upload.filename, data)
            document = DocumentModel(**{k: v for k, v in asdict(record).items() if k != "sha256"})
            results.append(UploadResult(
                filename=name, status="indexed", document=document,
                message=f"Indexed {record.pages} pages as {record.chunks} passages.",
            ))
        except DuplicateDocumentError as exc:
            results.append(UploadResult(filename=name, status="duplicate", message=exc.message))
        except (PDFError, OllamaError) as exc:
            logger.info("Could not index %s (%s): %s", name, exc.code, exc.message)
            results.append(UploadResult(filename=name, status="error", message=exc.message))
            first_error = first_error or (exc.status_code, exc.code, exc.message)

    body = UploadResponse(results=results).model_dump()
    succeeded = sum(r.status != "error" for r in results)
    if succeeded == 0 and first_error:
        status, code, message = first_error
        return JSONResponse(status_code=status, content={**error_body(code, message), **body})
    return JSONResponse(status_code=207 if first_error else 200, content=body)


@app.delete("/api/documents/{document_id}", status_code=204, tags=["documents"],
            responses={404: {"model": ErrorResponse}})
async def delete_document(request: Request, document_id: str, rag: RAGService = Depends(get_rag)) -> Response:
    async with request.app.state.index_lock:
        deleted = rag.store.delete_document(document_id)
    if not deleted:
        return JSONResponse(status_code=404, content=error_body("not_found", "Document not found."))
    return Response(status_code=204)


@app.delete("/api/documents", status_code=204, tags=["documents"])
async def clear_documents(request: Request, rag: RAGService = Depends(get_rag)) -> Response:
    async with request.app.state.index_lock:
        rag.store.clear()
    return Response(status_code=204)


@app.post("/api/ask", response_model=AskResponse, tags=["question answering"],
          responses={422: {"model": ErrorResponse}, 502: {"model": ErrorResponse},
                     503: {"model": ErrorResponse}, 504: {"model": ErrorResponse}})
async def ask(payload: AskRequest, rag: RAGService = Depends(get_rag)) -> AskResponse:
    """Answer a question from the indexed PDFs and return the answer with the retrieved passages."""
    result = await rag.answer(payload.question, payload.top_k or settings.top_k)
    return AskResponse(
        question=result.question,
        answer=result.answer,
        status=result.status,
        sources=[SourceModel(**asdict(s)) for s in result.sources],
        model=rag.client.llm_model,
        retrieval_ms=result.retrieval_ms,
        generation_ms=result.generation_ms,
    )
