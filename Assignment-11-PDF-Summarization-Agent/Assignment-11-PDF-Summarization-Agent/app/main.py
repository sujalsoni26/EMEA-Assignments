"""FastAPI application: PDF Summarization Agent (Llama 3 via Ollama)."""

from __future__ import annotations

import asyncio
import json
import logging
import time
from contextlib import asynccontextmanager
from pathlib import Path
from typing import AsyncIterator

from fastapi import Depends, FastAPI, File, Form, Request, UploadFile
from fastapi.concurrency import run_in_threadpool
from fastapi.encoders import jsonable_encoder
from fastapi.exceptions import RequestValidationError
from fastapi.responses import FileResponse, JSONResponse, StreamingResponse
from fastapi.staticfiles import StaticFiles

from .agent import AgentResult, PDFSummarizationAgent, ProgressEvent, SummaryLength
from .config import settings
from .ollama_client import OllamaClient, OllamaError
from .pdf_extractor import ExtractedDocument, PDFError, extract_pdf, validate_upload
from .schemas import (
    ConfigResponse,
    DocumentInfo,
    ErrorResponse,
    HealthResponse,
    SectionNotesModel,
    SummaryResponse,
    SummaryStats,
)

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
logger = logging.getLogger("pdf_agent")

STATIC_DIR = Path(__file__).parent / "static"


@asynccontextmanager
async def lifespan(app: FastAPI):
    app.state.ollama = OllamaClient(
        settings.ollama_base_url, settings.ollama_model, settings.request_timeout, settings.context_tokens
    )
    # Ollama processes one generation at a time; queue requests instead of overloading it.
    app.state.llm_lock = asyncio.Lock()
    logger.info("Using Ollama at %s with model '%s'", settings.ollama_base_url, settings.ollama_model)
    yield
    await app.state.ollama.aclose()


app = FastAPI(
    title="PDF Summarization Agent",
    description="Upload a PDF and get a structured summary generated by Llama 3 running locally through Ollama.",
    version="1.0.0",
    lifespan=lifespan,
)
app.mount("/static", StaticFiles(directory=STATIC_DIR), name="static")


def get_ollama(request: Request) -> OllamaClient:
    return request.app.state.ollama


# --------------------------------------------------------------------------- #
# Error handling: every error is returned as {"error": {"code", "message"}}
# --------------------------------------------------------------------------- #
def error_body(code: str, message: str) -> dict:
    return {"error": {"code": code, "message": message}}


@app.exception_handler(PDFError)
async def pdf_error_handler(request: Request, exc: PDFError) -> JSONResponse:
    logger.info("Rejected upload (%s): %s", exc.code, exc.message)
    return JSONResponse(status_code=exc.status_code, content=error_body(exc.code, exc.message))


@app.exception_handler(OllamaError)
async def ollama_error_handler(request: Request, exc: OllamaError) -> JSONResponse:
    logger.warning("Model error (%s): %s", exc.code, exc.message)
    return JSONResponse(status_code=exc.status_code, content=error_body(exc.code, exc.message))


@app.exception_handler(RequestValidationError)
async def validation_error_handler(request: Request, exc: RequestValidationError) -> JSONResponse:
    errors = exc.errors()
    message = "Invalid request."
    if errors:
        first = errors[0]
        field = str(first.get("loc", ["", ""])[-1])
        if first.get("type") == "missing" and field == "file":
            message = "No file was uploaded. Please choose a PDF document."
        elif field == "length":
            message = "Invalid summary length. Choose 'brief', 'standard' or 'detailed'."
        else:
            message = f"Invalid value for '{field}': {first.get('msg')}"
    return JSONResponse(status_code=422, content=error_body("validation_error", message))


@app.exception_handler(Exception)
async def unhandled_error_handler(request: Request, exc: Exception) -> JSONResponse:
    logger.exception("Unexpected error while handling %s %s", request.method, request.url.path)
    return JSONResponse(status_code=500, content=error_body("internal_error", "An unexpected error occurred. Please try again."))


# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #
async def read_and_extract(file: UploadFile) -> tuple[ExtractedDocument, int]:
    """Validate the upload and extract its text. Raises PDFError on any problem."""
    started = time.perf_counter()
    # Read at most one byte more than the limit, so huge uploads are rejected cheaply.
    data = await file.read(settings.max_file_bytes + 1)
    validate_upload(file.filename, data, settings.max_file_bytes)
    document = await run_in_threadpool(
        extract_pdf, data, file.filename or "document.pdf", max_pages=settings.max_pages, min_words=settings.min_words
    )
    return document, int((time.perf_counter() - started) * 1000)


def build_response(
    result: AgentResult, document: ExtractedDocument, length: SummaryLength, extraction_ms: int, model: str
) -> SummaryResponse:
    return SummaryResponse(
        title=result.title,
        tldr=result.tldr,
        summary=result.summary,
        key_points=result.key_points,
        sections=[SectionNotesModel(start_page=s.start_page, end_page=s.end_page, notes=s.notes) for s in result.sections],
        length=length,
        document=DocumentInfo(
            filename=document.filename,
            pages=document.page_count,
            words=document.word_count,
            title=document.title,
            skipped_pages=document.skipped_pages,
        ),
        stats=SummaryStats(
            model=model,
            strategy=result.strategy,
            chunks=result.chunks,
            llm_calls=result.llm_calls,
            extraction_ms=extraction_ms,
            summarization_ms=result.duration_ms,
        ),
    )


