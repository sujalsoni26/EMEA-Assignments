@app.get("/api/health", response_model=HealthResponse, tags=["meta"])
async def health(client: OllamaClient = Depends(get_ollama)) -> HealthResponse:
    """Check that Ollama is reachable and the Llama 3 model is installed."""
    try:
        available = await client.is_model_available()
    except OllamaError as exc:
        return HealthResponse(status="unavailable", ollama_reachable=False, model=client.model, model_available=False, message=exc.message)
    if not available:
        return HealthResponse(
            status="degraded",
            ollama_reachable=True,
            model=client.model,
            model_available=False,
            message=f"Ollama is running but the model '{client.model}' is missing. Run `ollama pull {client.model}`.",
        )
    return HealthResponse(status="ok", ollama_reachable=True, model=client.model, model_available=True, message="Ready.")


ERROR_RESPONSES = {
    400: {"model": ErrorResponse, "description": "No file or an empty file was uploaded."},
    413: {"model": ErrorResponse, "description": "The file is larger than the allowed size."},
    415: {"model": ErrorResponse, "description": "The file is not a PDF."},
    422: {"model": ErrorResponse, "description": "Corrupted, encrypted or scanned PDF, or invalid options."},
    502: {"model": ErrorResponse, "description": "The model returned an invalid response."},
    503: {"model": ErrorResponse, "description": "Ollama is not running or the model is not installed."},
    504: {"model": ErrorResponse, "description": "The model did not respond in time."},
}


@app.post("/api/summarize", response_model=SummaryResponse, responses=ERROR_RESPONSES, tags=["summarization"])
async def summarize(
    request: Request,
    file: UploadFile = File(..., description="The PDF document to summarise."),
    length: SummaryLength = Form(SummaryLength.standard),
    client: OllamaClient = Depends(get_ollama),
) -> SummaryResponse:
    """Summarise a PDF and return the complete result as JSON."""
    document, extraction_ms = await read_and_extract(file)
    agent = PDFSummarizationAgent(client, settings)
    async with request.app.state.llm_lock:
        result = await agent.run(document, length)
    return build_response(result, document, length, extraction_ms, client.model)


@app.post("/api/summarize/stream", responses=ERROR_RESPONSES, tags=["summarization"])
async def summarize_stream(
    request: Request,
    file: UploadFile = File(..., description="The PDF document to summarise."),
    length: SummaryLength = Form(SummaryLength.standard),
    client: OllamaClient = Depends(get_ollama),
) -> StreamingResponse:
    """Summarise a PDF and stream progress as newline-delimited JSON (NDJSON).

    Each line is one event: ``{"type": "progress", ...}``, then either
    ``{"type": "result", "data": {...}}`` or ``{"type": "error", "error": {...}}``.
    Upload problems are reported before streaming starts, with a normal HTTP error status.
    """
    document, extraction_ms = await read_and_extract(file)
    queue: asyncio.Queue[dict | None] = asyncio.Queue()

    async def report(event: ProgressEvent) -> None:
        await queue.put({"type": "progress", **event.__dict__})

    async def worker() -> None:
        try:
            await report(ProgressEvent("extracted", f"Extracted text from '{document.filename}' in {extraction_ms} ms."))
            lock: asyncio.Lock = request.app.state.llm_lock
            if lock.locked():
                await report(ProgressEvent("queued", "Waiting for another summary to finish…"))
            async with lock:
                result = await PDFSummarizationAgent(client, settings).run(document, length, report)
            response = build_response(result, document, length, extraction_ms, client.model)
            await queue.put({"type": "result", "data": jsonable_encoder(response)})
        except OllamaError as exc:
            logger.warning("Model error (%s): %s", exc.code, exc.message)
            await queue.put({"type": "error", "error": {"code": exc.code, "message": exc.message}})
        except asyncio.CancelledError:
            raise
        except Exception:
            logger.exception("Unexpected error while summarising %s", document.filename)
            await queue.put({"type": "error", "error": {"code": "internal_error", "message": "An unexpected error occurred. Please try again."}})
        finally:
            await queue.put(None)

    async def events() -> AsyncIterator[str]:
        task = asyncio.create_task(worker())
        try:
            while True:
                event = await queue.get()
                if event is None:
                    break
                yield json.dumps(event) + "\n"
        finally:
            # The client went away (or we finished): make sure the worker stops.
            if not task.done():
                logger.info("Client disconnected; cancelling summarisation of %s", document.filename)
                task.cancel()

    return StreamingResponse(events(), media_type="application/x-ndjson", headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"})
